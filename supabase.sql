-- Jalankan di Supabase Dashboard > SQL Editor.
create table if not exists public.jadwal (
  id bigint generated by default as identity primary key,
  nama text not null,
  tanggal date not null,
  tempat text not null,
  jam text not null,
  khadim text default '',
  created_at timestamptz not null default now()
);
create table if not exists public.dokumentasi (
  id bigint generated by default as identity primary key,
  judul text not null default '',
  path text not null,
  created_at timestamptz not null default now()
);
alter table public.jadwal enable row level security;
alter table public.dokumentasi enable row level security;
-- Pengunjung boleh membaca konten publik.
create policy "Public read jadwal" on public.jadwal for select to anon, authenticated using (true);
create policy "Public read dokumentasi" on public.dokumentasi for select to anon, authenticated using (true);
-- Hanya pengguna yang login melalui Supabase Auth boleh mengubah konten.
create policy "Authenticated insert jadwal" on public.jadwal for insert to authenticated with check (true);
create policy "Authenticated delete jadwal" on public.jadwal for delete to authenticated using (true);
create policy "Authenticated insert dokumentasi" on public.dokumentasi for insert to authenticated with check (true);
create policy "Authenticated delete dokumentasi" on public.dokumentasi for delete to authenticated using (true);

-- Bucket dokumentasi untuk foto publik.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('dokumentasi', 'dokumentasi', true, 5242880, array['image/jpeg','image/png','image/webp'])
on conflict (id) do update set public = true, file_size_limit = 5242880;
create policy "Public view dokumentasi files" on storage.objects for select to anon, authenticated using (bucket_id = 'dokumentasi');
create policy "Authenticated upload dokumentasi files" on storage.objects for insert to authenticated with check (bucket_id = 'dokumentasi');
create policy "Authenticated delete dokumentasi files" on storage.objects for delete to authenticated using (bucket_id = 'dokumentasi');

